//! Decides whether a pasteboard change may be recorded (SPEC §3.3–5.5).

use crate::model::ClipContents;
use crate::uti;

/// Clips larger than this are never stored.
pub const MAX_CLIP_BYTES: usize = 50 * 1024 * 1024;

/// Markers password managers put on secrets (nspasteboard.org and 1Password).
pub const CONFIDENTIAL_TYPES: &[&str] = &["org.nspasteboard.ConcealedType"];
pub const CONFIDENTIAL_PREFIXES: &[&str] = &["com.agilebits.onepassword"];

/// Markers for clipboard data that apps write temporarily.
pub const TRANSIENT_TYPES: &[&str] = &[
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
];

/// Apps ignored on a fresh install.
pub const DEFAULT_IGNORED_APPS: &[&str] = &["com.apple.keychainaccess", "com.apple.Passwords"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SkipReason {
    Empty,
    TooLarge,
    Confidential,
    Transient,
    IgnoredType(String),
    IgnoredApp(String),
}

#[derive(Debug, Clone, Default)]
pub struct PrivacyFilter {
    pub ignore_confidential: bool,
    pub ignore_transient: bool,
    pub ignored_types: Vec<String>,
    pub ignored_apps: Vec<String>,
}

impl PrivacyFilter {
    /// `Ok(())` when the clip may be stored. `source_bundle_id` is the app the
    /// clip is attributed to (after `source_override`).
    pub fn check(
        &self,
        contents: &ClipContents,
        source_bundle_id: Option<&str>,
    ) -> Result<(), SkipReason> {
        if contents.is_empty() {
            return Err(SkipReason::Empty);
        }
        if contents.total_bytes() > MAX_CLIP_BYTES {
            return Err(SkipReason::TooLarge);
        }
        for t in contents.types() {
            if self.ignore_confidential
                && (CONFIDENTIAL_TYPES.contains(&t)
                    || CONFIDENTIAL_PREFIXES.iter().any(|p| t.starts_with(p)))
            {
                return Err(SkipReason::Confidential);
            }
            if self.ignore_transient && TRANSIENT_TYPES.contains(&t) {
                return Err(SkipReason::Transient);
            }
            if self.ignored_types.iter().any(|ignored| ignored == t) {
                return Err(SkipReason::IgnoredType(t.to_string()));
            }
        }
        if let Some(bundle_id) = source_bundle_id
            && self
                .ignored_apps
                .iter()
                .any(|app| app.eq_ignore_ascii_case(bundle_id))
        {
            return Err(SkipReason::IgnoredApp(bundle_id.to_string()));
        }
        Ok(())
    }
}

/// Bundle ID declared by the producing app through `org.nspasteboard.source`.
pub fn source_override(contents: &ClipContents) -> Option<String> {
    contents
        .first_string(uti::SOURCE)
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
}

/// Drops `dyn.*` representations when an entry has other types, so stored
/// clips don't carry opaque, app-private data that can't be named.
pub fn sanitize(mut contents: ClipContents) -> ClipContents {
    for entry in &mut contents.entries {
        let has_named = entry
            .representations
            .iter()
            .any(|r| !r.uti.starts_with("dyn."));
        if has_named {
            entry.representations.retain(|r| !r.uti.starts_with("dyn."));
        }
    }
    contents.entries.retain(|e| !e.representations.is_empty());
    contents
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{PasteboardEntry, Representation};

    fn clip(types: &[&str]) -> ClipContents {
        ClipContents::new(vec![PasteboardEntry::new(
            types.iter().map(|t| Representation::new(*t, "x")).collect(),
        )])
    }

    fn filter() -> PrivacyFilter {
        PrivacyFilter {
            ignore_confidential: true,
            ignore_transient: true,
            ignored_types: vec!["com.example.secret".into()],
            ignored_apps: DEFAULT_IGNORED_APPS.iter().map(|s| s.to_string()).collect(),
        }
    }

    #[test]
    fn accepts_ordinary_text() {
        assert_eq!(
            filter().check(&clip(&[uti::PLAIN_TEXT]), Some("com.apple.Notes")),
            Ok(())
        );
        assert_eq!(filter().check(&clip(&[uti::PLAIN_TEXT]), None), Ok(()));
    }

    #[test]
    fn rejects_marked_content() {
        let f = filter();
        assert_eq!(
            f.check(
                &clip(&[uti::PLAIN_TEXT, "org.nspasteboard.ConcealedType"]),
                None
            ),
            Err(SkipReason::Confidential)
        );
        assert_eq!(
            f.check(
                &clip(&[uti::PLAIN_TEXT, "com.agilebits.onepassword7"]),
                None
            ),
            Err(SkipReason::Confidential)
        );
        assert_eq!(
            f.check(
                &clip(&[uti::PLAIN_TEXT, "org.nspasteboard.TransientType"]),
                None
            ),
            Err(SkipReason::Transient)
        );
        assert_eq!(
            f.check(&clip(&["com.example.secret"]), None),
            Err(SkipReason::IgnoredType("com.example.secret".into()))
        );
        assert_eq!(
            f.check(&clip(&[uti::PLAIN_TEXT]), Some("com.apple.KeychainAccess")),
            Err(SkipReason::IgnoredApp("com.apple.KeychainAccess".into()))
        );
    }

    #[test]
    fn toggles_disable_checks() {
        let f = PrivacyFilter::default();
        assert_eq!(
            f.check(&clip(&["org.nspasteboard.ConcealedType"]), None),
            Ok(())
        );
        assert_eq!(
            f.check(&clip(&["org.nspasteboard.TransientType"]), None),
            Ok(())
        );
    }

    #[test]
    fn empty_and_oversized() {
        let f = filter();
        assert_eq!(
            f.check(&ClipContents::default(), None),
            Err(SkipReason::Empty)
        );
        let big = ClipContents::new(vec![PasteboardEntry::new(vec![Representation::new(
            uti::PNG,
            vec![0u8; MAX_CLIP_BYTES + 1],
        )])]);
        assert_eq!(f.check(&big, None), Err(SkipReason::TooLarge));
    }

    #[test]
    fn source_marker_and_sanitizing() {
        let mut c = clip(&[uti::PLAIN_TEXT]);
        c.entries[0]
            .representations
            .push(Representation::new(uti::SOURCE, "com.example.app\n"));
        assert_eq!(source_override(&c).as_deref(), Some("com.example.app"));
        assert_eq!(source_override(&clip(&[uti::PLAIN_TEXT])), None);

        let messy = ClipContents::new(vec![
            PasteboardEntry::new(vec![
                Representation::new(uti::PLAIN_TEXT, "a"),
                Representation::new("dyn.ah62d4rv4gu8y", "?"),
            ]),
            PasteboardEntry::new(vec![Representation::new("dyn.only", "?")]),
        ]);
        let clean = sanitize(messy);
        assert_eq!(clean.entries.len(), 2);
        assert_eq!(clean.entries[0].representations.len(), 1);
        assert_eq!(clean.entries[1].representations[0].uti, "dyn.only");
    }
}
